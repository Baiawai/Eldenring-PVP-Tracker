const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('static/app.js', 'utf8');
const start = source.indexOf('// TRACKER_ACTION_START');
const end = source.indexOf('// TRACKER_ACTION_END');
assert(start >= 0 && end > start);
const context = {};
vm.runInNewContext(source.slice(start, end), context);
const calls = [];
let errors = 0;
const jquery = {ajax(options) { calls.push(options); }};
context.sendTrackerAction(jquery, {url:'/stop', error() { errors++; }});
assert.equal(calls[0].type, 'POST');
calls[0].error({status:405}, 'error', 'method');
assert.equal(calls[1].type, 'GET');
assert.equal(calls[1].url, '/stop');
calls[1].error({status:500});
assert.equal(errors, 1);
context.sendTrackerAction(jquery, {url:'/start', error() { errors++; }});
calls[2].error({status:403});
assert.equal(calls.length, 3);
assert.equal(errors, 2);
